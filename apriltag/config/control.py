"""제어 — 잰 값을 보고 어떻게 움직일지 정하는 값.

    얼마나 맞춰야 하나   도킹 허용치. **이 둘이 이 파일의 뿌리다**
    어떻게 다가가나      전진 조각 크기, 안전 배수, 처음 다가가는 비율
    언제 끝내나         태그가 화면에서 잘리기 직전 + 여유
    회전을 어떻게 주나   IMU 폐루프의 문턱들
    잃었을 때           탐색 안전망

여기 없는 것
    멈출 거리    숫자로 안 정한다. 태그가 화면에서 잘리기 직전까지 가고
                 그때 다음 태그로 넘긴다(TAG_CUT_MARGIN_PX).
    FWD_*        직진 시간 모델. 다른 팀 코드라 src/models/control/fwd_time_model.py

LAT_TOL_M / HEAD_TOL_DEG 는 **탑재부가 요구하는 정밀도**여야 한다. 지금 값은
우리 쪽 사정(명령 하한 17mm)만 보고 정한 것이라, 현장 사양을 받으면 바꿔야 한다.
검출 쪽 흔들림 문턱도 여기서 파생되므로 같이 따라온다.
"""

# ── 얼마나 맞춰야 하나 (이 파일의 뿌리) ─────────────────────────────────────

LAT_TOL_M = 0.030              # |lateral| 이 이보다 작으면 됐다고 본다. 명령 하한이 17mm 라 그 밑은 무의미
HEAD_TOL_DEG = 2.0             # heading 허용치. 옆이동 3단계가 자동으로 0 으로 만든다

# ── 어떻게 다가가나 ─────────────────────────────────────────────────────────

STEP_M = 1.0                   # 직진 한 조각. 3m 를 1m 씩이면 1.46배 느려짐(측정 포함)
FWD_SAFETY = 0.9               # 한 번에 명령하는 거리 = 남은 거리 x 이 값.
                               # 전진은 개루프고 속도가 5% 빠르면 3m 에 15cm 지나친다.
                               # 모자라게 가면 다음 사이클에 또 가면 되지만
                               # 지나치면 되돌리기 비싸다(후진 모델이 없다)
WARMUP_FRACTION = 0.33         # 맨 처음엔 옆정렬 말고 이 비율만큼 먼저 다가간다.
                               # lateral 오차 = heading 오차 x 거리라, 5m 에서
                               # 옆정렬은 +-314mm 잡음을 쫓는 꼴이다
FWD_ABORT_K = 3.0              # 전진 중 heading 감시의 잡음 하한 배수.
                               # 허용치 자체는 asin(LAT_TOL_M / 남은거리) 로 계산된다
SIDESTEP_BACKWARD_GAIN_DEG = 0.0   # 후진이 회전을 이만큼 넘게 아끼면 후진. 0 = 회전 작은 쪽

# ── 언제 끝내나 ─────────────────────────────────────────────────────────────

TAG_CUT_MARGIN_PX = 30.0       # 태그가 화면 가장자리에서 이만큼 안으로 오면 "잘리기 직전".
                               # 정지 명령 뒤 관성 0.15초 동안 최대 9px 줄어드니 3배 여유다
DOCK_EXTRA_M = 0.0             # 마지막 태그 면을 지나 더 갈 거리 [m].
                               # 태그가 탑재부 끝에 안 붙어 있으면 그만큼 양수로.
                               # **현장에서 자로 재야 아는 값** — 카메라도 태그도 모른다

# ── 루프 ────────────────────────────────────────────────────────────────────

MAX_STEPS = 30                 # 이 단계 수를 넘기면 수렴 실패로 보고 멈춘다.
                               # 탐색 걸음은 여기 안 센다(SEARCH_MAX_ROUNDS 가 따로 막는다)
HOLD_RETRY_SEC = 0.2           # hold 판정 뒤 다시 재기까지 (dock 전용. dock_live 는 프레임이 곧 주기)
SETTLE_SEC = 0.15              # 시간 명령을 끊은 뒤 관성이 잦아들 시간

# ── 회전 (IMU 폐루프) ───────────────────────────────────────────────────────
#
# 회전은 시간이 아니라 각도로 명령한다 — CanDriver.rotate_by() 가 IMU 를 보며
# 목표각에서 끊는다. 그래서 아래 ROT_T0_SEC / ROT_DEG_PER_SEC 가 미측정 가정값
# 이어도 **결과가 안 바뀐다**. 화면의 "예상 N초", 워치독 상한, IMU 가 없을 때의
# 비상 폴백에만 쓰인다.

ROT_T0_SEC = 0.5               # 회전 명령 지연 [s].  **미측정 가정값** (직진 t0=0.507 을 빌림)
ROT_DEG_PER_SEC = 15.0         # 회전 각속도 [도/s].  **미측정 가정값**
ROT_MIN_SEC = 1.0              # 직진과 같다고 가정. 확인 필요
ROT_MAX_SEC = 15.0             # 워치독 하한. 실제 상한은 각도에 비례해 늘어난다(rot_timeout_sec)
ROT_WATCHDOG_GAIN = 3.0        # 워치독 = 예상시간 x 이 값. 각속도가 1/3 이어도 버틴다
ROT_LEAD_DEG = 0.0             # 관성만큼 미리 끊는 각. 0 이면 안 끊음.
                               # rotate_by 가 회전마다 overshoot 를 재서 로그로 남긴다 — 그 평균을 넣을 것
ROT_WRONG_WAY_DEG = 5.0        # 반대로 이만큼 돌면 CAN 회전 부호가 뒤집힌 것. 즉시 정지
ROT_POLL_SEC = 0.01            # 회전 중 IMU 확인 주기. 10ms 면 15도/s 에서 0.15도/틱
ROT_SETTLE_MAX_SEC = 1.0       # 정지 명령 후 멎기를 기다리는 상한
ROT_SETTLE_MIN_SEC = 0.2       # 최소 이만큼은 기다린다 (명령 반영 지연)
ROT_SETTLE_POLL_SEC = 0.05     # 멎었나 확인하는 주기
ROT_SETTLE_RATE_K = 3.0        # 멎음 판정 = 보정 때 잰 잡음 x 이 값 [도/s]
ROT_SETTLE_RATE_FLOOR = 1.0    # 그 판정의 하한 [도/s]. 보정 전이면 이 값을 쓴다

# ── 태그를 잃었을 때 (최종 안전망) ──────────────────────────────────────────
#
# 거의 안 쓰일 길이다. 잘 짜여 있으면 태그를 잃을 일이 별로 없다.
# 그래도 났을 때 hold 만 반복하면 영영 못 빠져나오므로 넣는다.

SEARCH_AFTER_MISSES = 3        # **아무 태그도** 못 본 사이클이 이만큼이면 탐색 시작 (약 15초)
SEARCH_BACKUP_M = 0.5          # 쓸어도 못 찾으면 이만큼 후진.
                               # 후진이 두 실종 원인(너무 가까움 / 좌우로 벗어남)을
                               # 한꺼번에 완화해서 원인 판별이 필요 없다
SEARCH_MAX_ROUNDS = 3          # 쓸기+후진을 이만큼 하고 못 찾으면 정지하고 사람을 부른다
