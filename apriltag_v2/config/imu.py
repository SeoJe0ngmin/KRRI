"""IMU — D435i 자이로 자체에 관한 값.

이 IMU(BMI055)는 6축이라 **자력계가 없다.** 그래서 절대 방위각은 못 잰다.
할 수 있는 것은 "영점 선언 후 몇 도 돌았나"뿐이고, 그게 정확히 회전 명령에
필요한 값이다. 절대 기준은 태그가 보일 때 heading 으로 다시 잡는다.

    카메라(태그)   heading   태그 축 기준. **절대**. 느리고(30프레임=1초) 회전 중엔 안 보임
    IMU(자이로)    yaw       영점 기준. **상대**. 빠르고(200Hz) 항상 보이지만 흘러감

둘이 서로의 약점을 덮는다 — IMU 가 흘러가도 매 사이클 태그가 기준을 다시
잡아주고, 태그가 안 보이는 회전 구간을 IMU 가 메운다.

여기 없는 것
    바이어스·회전축·잡음   **매번 다시 잰다.** 자이로 바이어스는 온도에 따라
        변해서 적어두면 틀린다. run.py 가 시작할 때 calibrate() 를 부르고,
        그 자리에서 잡은 값을 그대로 쓴다.
    회전 명령 문턱(ROT_*)  회전을 어떻게 줄지는 제어의 몫이라 config/control.py

IMU_YAW_SIGN 은 2026-09-06 현장 노트북에서 실물 확정했다 — imu_check 로
카메라를 반시계로 돌려 +가 나오는 부호를 골랐다. 카메라를 다시 달거나
장비가 바뀌면 같은 방법으로 재확인할 것.
"""

IMU_GYRO_HZ = 200              # 자이로 샘플 주파수. 이 장치의 유효값은 200/400 뿐
IMU_YAW_SIGN = +1.0            # 자이로 -> 우리 부호규약(+가 반시계).
                               # 2026-09-06 실물 확정 — -1.0 은 옛 y축 단독 투영
                               # 시절 값. 중력축 투영으로 바꾸며 부호가 뒤집혔다
IMU_BIAS_SEC = 2.0             # 정지 바이어스 측정 시간 [s].
                               # 미보정이면 5.5도/분 흘러가고, 2초 보정하면 1.0도/분
IMU_STALE_SEC = 0.3            # 이만큼 샘플이 안 오면 죽은 것으로 본다.
                               # 죽은 계기판으로 회전하면 못 세운다
IMU_DT_GAP_SAMPLES = 10        # 샘플 간격이 이 개수를 넘게 벌어지면 그 구간은 적분하지 않는다.
