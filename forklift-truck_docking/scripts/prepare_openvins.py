"""Stage pinned, unchanged estimator sources with a minimal ROS Jazzy build.

Only the three CMakeLists.txt files are generated. Upstream ROS visualizers and
example executables are not needed by our adapter (and use older ROS headers).
The immutable git checkout is kept outside the colcon source discovery tree.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile

COMMIT = '69488123ed9362dd44b6f28e7f4680abbff1442b'
SOURCES = {
    'ov_core': 'dummy.cpp cpi/CpiV1.cpp cpi/CpiV2.cpp sim/BsplineSE3.cpp '
               'track/TrackBase.cpp track/TrackAruco.cpp track/TrackDescriptor.cpp '
               'track/TrackKLT.cpp track/TrackSIM.cpp types/Landmark.cpp feat/Feature.cpp '
               'feat/FeatureDatabase.cpp feat/FeatureInitializer.cpp utils/print.cpp',
    'ov_init': 'dummy.cpp ceres/Factor_GenericPrior.cpp ceres/Factor_ImageReprojCalib.cpp '
               'ceres/Factor_ImuCPIv1.cpp ceres/State_JPLQuatLocal.cpp '
               'init/InertialInitializer.cpp dynamic/DynamicInitializer.cpp '
               'static/StaticInitializer.cpp sim/SimulatorInit.cpp',
    'ov_msckf': 'dummy.cpp sim/Simulator.cpp state/State.cpp state/StateHelper.cpp '
                'state/Propagator.cpp core/VioManager.cpp core/VioManagerHelper.cpp '
                'update/UpdaterHelper.cpp update/UpdaterMSCKF.cpp update/UpdaterSLAM.cpp '
                'update/UpdaterZeroVelocity.cpp',
}
DEPS = {'ov_core': [], 'ov_init': ['ov_core'], 'ov_msckf': ['ov_core', 'ov_init']}
MARKER = '.docking-v6-generated.json'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def cmake(package):
    deps = DEPS[package]
    finds = '\n'.join(f'find_package({dep} REQUIRED)' for dep in deps)
    sources = '\n  '.join('src/'+name for name in SOURCES[package].split())
    return f'''# Generated by KRRI v6. Estimator .cpp/.h files are unchanged upstream.
cmake_minimum_required(VERSION 3.16)
project({package})
set(CMAKE_CXX_STANDARD 17)
set(CMAKE_CXX_STANDARD_REQUIRED ON)
find_package(ament_cmake REQUIRED)
find_package(rclcpp REQUIRED)
find_package(Eigen3 REQUIRED)
find_package(OpenCV 4 REQUIRED)
find_package(Boost REQUIRED COMPONENTS system filesystem thread date_time)
find_package(Ceres REQUIRED)
{finds}
add_library({package}_lib SHARED
  {sources})
target_compile_definitions({package}_lib PUBLIC ROS_AVAILABLE=2 ENABLE_ARUCO_TAGS=0)
target_include_directories({package}_lib PUBLIC src ${{EIGEN3_INCLUDE_DIRS}}
  ${{Boost_INCLUDE_DIRS}} ${{CERES_INCLUDE_DIRS}} ${{OpenCV_INCLUDE_DIRS}})
ament_target_dependencies({package}_lib rclcpp {' '.join(deps)})
target_link_libraries({package}_lib ${{Boost_LIBRARIES}} ${{CERES_LIBRARIES}} ${{OpenCV_LIBS}})
install(TARGETS {package}_lib LIBRARY DESTINATION lib)
install(DIRECTORY src/ DESTINATION include FILES_MATCHING PATTERN "*.h" PATTERN "*.hpp")
ament_export_include_directories(include)
ament_export_libraries({package}_lib)
ament_export_dependencies(rclcpp {' '.join(deps)})
ament_package()
'''.encode()


def prepare(source, target):
    source, target = Path(source), Path(target)
    def git(*args):
        return subprocess.check_output(['git', '-C', str(source), *args])
    if git('rev-parse', 'HEAD').decode().strip() != COMMIT:
        raise ValueError('unexpected OpenVINS commit')
    if git('status', '--porcelain').strip():
        raise ValueError('OpenVINS upstream checkout contains local changes')
    files = {}
    with tarfile.open(fileobj=io.BytesIO(git('archive', 'HEAD', *SOURCES, 'LICENSE'))) as archive:
        for member in archive:
            if member.isdir():
                continue
            path = Path(member.name)
            if not member.isfile() or path.is_absolute() or '..' in path.parts:
                raise ValueError('unexpected archive entry: '+member.name)
            files[member.name] = archive.extractfile(member).read()
    for package in SOURCES:
        for name in SOURCES[package].split():
            if package+'/src/'+name not in files:
                raise ValueError('upstream source missing: '+name)
        files[package+'/CMakeLists.txt'] = cmake(package)
    # Re-running may update generated build files, but never overwrite edits.
    old = {}
    if target.exists():
        marker = target/MARKER
        if not marker.is_file():
            raise ValueError('existing unmanaged build source: '+str(target))
        old = json.loads(marker.read_text())['files']
        for name, expected in old.items():
            p = target/name
            if not p.is_file() or p.is_symlink() or digest(p.read_bytes()) != expected:
                raise ValueError('modified generated source; preserve it before rebuilding: '+str(p))
        for p in target.rglob('*'):
            if p.is_symlink() or (p.is_file() and p.name != MARKER and p.relative_to(target).as_posix() not in old):
                raise ValueError('unmanaged file in generated source: '+str(p))
    target.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        p = target/name
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_bytes() != data:
            p.write_bytes(data)
    for name in old.keys()-files.keys():
        (target/name).unlink()
    (target/MARKER).write_text(json.dumps(dict(commit=COMMIT, files={k:digest(v) for k,v in files.items()}), indent=2))
    print('Prepared unchanged OpenVINS algorithms with C++17 library-only build: '+str(target))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source'); parser.add_argument('target')
    args = parser.parse_args()
    prepare(args.source, args.target)
